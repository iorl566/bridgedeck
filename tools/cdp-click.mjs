import http from 'node:http';
const PORT = 9347;
const get = (p) => new Promise((resolve, reject) => { http.get({ host: '127.0.0.1', port: PORT, path: p }, (res) => { let d=''; res.on('data', c=>d+=c); res.on('end', ()=>resolve(d)); }).on('error', reject); });
const slp = (ms) => new Promise((r) => setTimeout(r, ms));
const list = JSON.parse(await get('/json/list'));
const target = list.find((t) => t.type === 'page' && t.url.includes('test.html'));
console.log('target', target && target.url);
const ws = new WebSocket(target.webSocketDebuggerUrl);
const pending = new Map(); let seq = 0;
ws.onmessage = (ev) => { try { const m = JSON.parse(String(ev.data)); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } } catch {} };
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
const send = (method, params={}) => new Promise((resolve) => { const id=++seq; pending.set(id, resolve); ws.send(JSON.stringify({id,method,params})); });
await send('Page.bringToFront');
await send('Input.dispatchMouseEvent',{type:'mouseMoved',x:74.66,y:264.59,button:'none',buttons:0,clickCount:0});
await send('Input.dispatchMouseEvent',{type:'mousePressed',x:74.66,y:264.59,button:'left',buttons:1,clickCount:1});
await send('Input.dispatchMouseEvent',{type:'mouseReleased',x:74.66,y:264.59,button:'left',buttons:0,clickCount:1});
await slp(300);
const out = await send('Runtime.evaluate',{expression:"document.getElementById('out').textContent",returnByValue:true});
console.log('out', out.result && out.result.result && out.result.result.value);
process.exit(0);
