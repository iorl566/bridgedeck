// dsh-plugin/scripts/build-skill-content.mjs —— 把仓库的 skill 嵌入 DSH 插件。
//
// 插件通过 ctx.skills.register 发布同一份技能；SKILL.md 正文嵌入静态模块，
// references 复制到 dsh-plugin/skill/ 作为 resourceBase，供按需读取。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, '..');
const source = path.resolve(pkg, '..', 'skill');
const target = path.join(pkg, 'skill');
const sourceFile = path.join(source, 'SKILL.md');
const text = fs.readFileSync(sourceFile, 'utf8');
const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
if (!match) throw new Error('SKILL.md 缺少 frontmatter');
const front = match[1];
const body = text.slice(match[0].length);
const name = (front.match(/^name:\s*(.+)$/m) || [])[1]?.trim();
const frontLines = front.split(/\r?\n/);
const descIndex = frontLines.findIndex((line) => /^description:/.test(line));
let description = '';
if (descIndex >= 0) {
  const inline = frontLines[descIndex].replace(/^description:\s*/, '').replace(/^\|\s*$/, '').trim();
  if (inline) {
    description = inline;
  } else {
    const parts = [];
    for (let index = descIndex + 1; index < frontLines.length; index += 1) {
      const line = frontLines[index];
      if (line && !/^\s/.test(line)) break;
      if (line.trim()) parts.push(line.trim());
    }
    description = parts.join('\n');
  }
}
if (!name || !description) throw new Error('SKILL.md frontmatter 缺少 name/description');

fs.rmSync(target, { recursive: true, force: true });
fs.mkdirSync(target, { recursive: true });
const copy = (from, to) => {
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    if (entry.name === '.bridge-skill.json') continue;
    const src = path.join(from, entry.name);
    const dst = path.join(to, entry.name);
    if (entry.isDirectory()) {
      fs.mkdirSync(dst, { recursive: true });
      copy(src, dst);
    } else {
      fs.copyFileSync(src, dst);
    }
  }
};
copy(source, target);

const banner = '// GENERATED by scripts/build-skill-content.mjs — do not edit.\n'
  + '// Source: ../../skill/SKILL.md; references are copied to ../skill/ for resourceBase.\n';
const out = path.join(pkg, 'lib', 'skill-content.generated.mjs');
fs.writeFileSync(out, `${banner}export const SKILL_NAME = ${JSON.stringify(name)};\n`
  + `export const SKILL_DESCRIPTION = ${JSON.stringify(description)};\n`
  + `export const SKILL_MARKDOWN = ${JSON.stringify(body)};\n`);
console.log(`skill content written: ${name} (${body.length} chars, references synced)`);
