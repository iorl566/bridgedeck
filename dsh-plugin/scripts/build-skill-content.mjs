// dsh-plugin/scripts/build-skill-content.mjs —— 把仓库技能与插件专属 references 嵌入 DSH 插件。
//
// 两个来源：
//   1) 仓库根 skill/（SKILL.md + references/*.md）—— 与 CLI/MCP 共用的主技能；
//   2) dsh-plugin/skill-extras/references/*.md —— 只在 DSH 插件里附带的补充参考
//      （actions-guide / transactions / evaluation / offline-testing）。
//
// 生成物：
//   - dsh-plugin/skill/**                     供 skill resourceBase 按需读取的目录树；
//   - dsh-plugin/lib/skill-content.generated.mjs  SKILL 正文 + 补充参考索引。
//
// 用法：
//   node dsh-plugin/scripts/build-skill-content.mjs          # 写生成物
//   node dsh-plugin/scripts/build-skill-content.mjs --check  # 只校验，未同步则 exit 1
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PKG = path.resolve(HERE, '..');
const REPO = path.resolve(PKG, '..');
const SOURCE = path.join(REPO, 'skill');
const EXTRAS = path.join(PKG, 'skill-extras');
const TARGET = path.join(PKG, 'skill');
const GENERATED = path.join(PKG, 'lib', 'skill-content.generated.mjs');

const BANNER = '// GENERATED by scripts/build-skill-content.mjs — do not edit.\n'
  + '// Source: ../../skill/SKILL.md + ./skill-extras/references/*.md; tree copied to ../skill/ for resourceBase.\n';

function parseSkill(text, label) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) throw new Error(label + ' 缺少 frontmatter');
  const front = match[1];
  const body = text.slice(match[0].length).replace(/\r\n/g, '\n');
  const name = (front.match(/^name:\s*(.+)$/m) || [])[1]?.trim();
  const frontLines = front.split(/\r?\n/);
  const descIndex = frontLines.findIndex((line) => /^description:/.test(line));
  let description = '';
  if (descIndex >= 0) {
    const inline = frontLines[descIndex].replace(/^description:\s*/, '').replace(/^\|\s*$/, '').trim();
    if (inline) {
      description = inline;
    } else {
      const parts = [];
      for (let index = descIndex + 1; index < frontLines.length; index += 1) {
        const line = frontLines[index];
        if (line && !/^\s/.test(line)) break;
        if (line.trim()) parts.push(line.trim());
      }
      description = parts.join('\n');
    }
  }
  if (!name || !description) throw new Error(label + ' frontmatter 缺少 name/description');
  return { name, description, body };
}

function listFiles(dir, base = dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full, base));
    else out.push({ relative: path.relative(base, full).split(path.sep).join('/'), absolute: full });
  }
  return out;
}

/** 解析 skill-extras 里的补充参考：`# 标题` + `> 摘要：...` 两行必须存在。 */
export function readSkillExtras(extrasDir = EXTRAS) {
  const dir = path.join(extrasDir, 'references');
  if (!fs.existsSync(dir)) throw new Error('缺少补充参考目录：' + path.relative(REPO, dir));
  const extras = [];
  for (const file of listFiles(dir)) {
    if (!file.relative.endsWith('.md')) continue;
    const text = fs.readFileSync(file.absolute, 'utf8');
    const title = (text.match(/^#\s+(.+)$/m) || [])[1]?.trim();
    const summary = (text.match(/^>\s*摘要：(.+)$/m) || [])[1]?.trim();
    if (!title) throw new Error('补充参考缺少一级标题：' + file.relative);
    if (!summary) throw new Error('补充参考缺少“> 摘要：”行：' + file.relative);
    extras.push({
      path: 'references/' + path.basename(file.relative),
      title,
      summary,
    });
  }
  if (!extras.length) throw new Error('skill-extras/references 为空：至少需要一篇补充参考');
  return extras.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

function expectedTree(extras) {
  const files = new Map();
  for (const file of listFiles(SOURCE)) {
    if (path.basename(file.absolute) === '.bridge-skill.json') continue;
    files.set(file.relative, fs.readFileSync(file.absolute));
  }
  for (const file of listFiles(EXTRAS)) {
    if (!file.relative.startsWith('references/')) continue;
    files.set(file.relative, fs.readFileSync(file.absolute));
  }
  for (const extra of extras) {
    if (!files.has(extra.path)) throw new Error('补充参考未被复制：' + extra.path);
  }
  return files;
}

function renderGenerated(parsed, extras) {
  return BANNER
    + 'export const SKILL_NAME = ' + JSON.stringify(parsed.name) + ';\n'
    + 'export const SKILL_DESCRIPTION = ' + JSON.stringify(parsed.description) + ';\n'
    + 'export const SKILL_MARKDOWN = ' + JSON.stringify(parsed.body) + ';\n'
    + '// 仅 DSH 插件附带的补充参考（生成自 ./skill-extras/references/*.md）。\n'
    + 'export const SKILL_EXTRA_REFERENCES = ' + JSON.stringify(extras, null, 2) + ';\n';
}

/**
 * 生成（或校验）技能生成物。
 * @param {{ check?: boolean }} [options]
 * @returns {{ problems: string[], changed: boolean, stats: { references: number, extras: number, generatedChars: number } }}
 */
export function buildSkillContent({ check = false } = {}) {
  const sourceText = fs.readFileSync(path.join(SOURCE, 'SKILL.md'), 'utf8');
  const parsed = parseSkill(sourceText, 'skill/SKILL.md');
  const extras = readSkillExtras();
  const expected = expectedTree(extras);
  const generatedText = renderGenerated(parsed, extras);
  const problems = [];

  const current = new Map();
  if (fs.existsSync(TARGET)) {
    for (const file of listFiles(TARGET)) current.set(file.relative, fs.readFileSync(file.absolute));
  }
  for (const [relative, buffer] of expected) {
    if (!current.has(relative)) problems.push('缺少文件：dsh-plugin/skill/' + relative);
    else if (!current.get(relative).equals(buffer)) problems.push('内容不同步：dsh-plugin/skill/' + relative);
  }
  for (const relative of current.keys()) {
    if (!expected.has(relative)) problems.push('多余文件（源里已删除）：dsh-plugin/skill/' + relative);
  }
  let currentGenerated = null;
  try {
    currentGenerated = fs.readFileSync(GENERATED, 'utf8');
  } catch {
    currentGenerated = null;
  }
  if (currentGenerated !== generatedText) problems.push('内容不同步：dsh-plugin/lib/skill-content.generated.mjs');

  if (!check) {
    fs.rmSync(TARGET, { recursive: true, force: true });
    fs.mkdirSync(TARGET, { recursive: true });
    for (const [relative, buffer] of expected) {
      const target = path.join(TARGET, relative);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, buffer);
    }
    fs.writeFileSync(GENERATED, generatedText, 'utf8');
    // 写盘成功即同步完成：上面的 problems 是写前差异，不再作为失败返回。
    problems.length = 0;
  }

  const referenced = expected.size;
  const rootReferences = [...expected.keys()].filter((relative) => relative.startsWith('references/')).length;
  return {
    problems,
    changed: problems.length > 0,
    stats: {
      name: parsed.name,
      references: rootReferences,
      extras: extras.length,
      generatedChars: generatedText.length,
      markdownChars: parsed.body.length,
      files: referenced,
    },
  };
}

export function checkSkillContent() {
  const result = buildSkillContent({ check: true });
  return result;
}

function main(argv) {
  const check = argv.includes('--check');
  const result = buildSkillContent({ check });
  if (check) {
    if (result.problems.length) {
      console.error('SKILL CONTENT CHECK FAILED（生成器未重跑或手工改过生成物）：');
      for (const problem of result.problems) console.error('  - ' + problem);
      console.error('修复：node dsh-plugin/scripts/build-skill-content.mjs');
      process.exit(1);
    }
    console.log('skill content check: clean (' + result.stats.name + '，' + result.stats.references
      + ' 篇参考（含 ' + result.stats.extras + ' 篇插件补充），' + result.stats.markdownChars + ' chars）');
    return;
  }
  if (result.problems.length) {
    console.error('SKILL CONTENT SYNC FAILED：');
    for (const problem of result.problems) console.error('  - ' + problem);
    process.exit(1);
  }
  console.log('skill content written: ' + result.stats.name + ' (' + result.stats.markdownChars + ' chars, '
    + result.stats.references + ' references incl. ' + result.stats.extras + ' plugin extras, '
    + result.stats.files + ' files synced)');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
