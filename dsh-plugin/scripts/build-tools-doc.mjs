#!/usr/bin/env node
// dsh-plugin/scripts/build-tools-doc.mjs —— 由工具 spec + 元数据生成 TOOLS.md。
//
// 生成物是模型/维护者的工具索引：分类、风险、幂等、副作用、协议方法与“失败后下一步”。
// 数据来源只有 buildToolSpecs（tools.mjs + tool-metadata.mjs），本脚本不手写任何清单。
//
// 用法：
//   node dsh-plugin/scripts/build-tools-doc.mjs          # 写 TOOLS.md
//   node dsh-plugin/scripts/build-tools-doc.mjs --check  # 只校验，漂移则 exit 1
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildToolSpecs } from '../lib/tools.mjs';
import {
  CATEGORIES,
  RISK_LEVELS,
  SIDE_EFFECTS,
  groupByCategory,
  summarizeMetadata,
  validateMetadataCoverage,
} from '../lib/tool-metadata.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PLUGIN_DIR = path.resolve(HERE, '..');
const OUTPUT = path.join(PLUGIN_DIR, 'TOOLS.md');

const RISK_LABEL = { read: '只读', write: '可写', destructive: '破坏性' };
const RISK_NOTE = {
  read: '不改变页面/浏览器状态（可能写本地文件）',
  write: '改页面/浏览器/会话状态，常规可恢复',
  destructive: '可能关闭窗口、执行任意 JS、审批/回放配方、撤销配对、更新安装或改全局设置',
};

function cell(text) {
  return String(text).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function riskCell(spec) {
  return RISK_LABEL[spec.risk] + '（`' + spec.risk + '`）';
}

function idempotentCell(spec) {
  return spec.idempotent ? '是' : '否';
}

function effectsCell(spec) {
  if (!spec.sideEffects.length) return '—';
  return spec.sideEffects.map((effect) => '`' + effect + '`').join(' ');
}

function methodsCell(spec) {
  if (!spec.methods.length) return '—（纯 CLI/本地）';
  return spec.methods.map((method) => '`' + method + '`').join(' ');
}

/** @param {Array} specs buildToolSpecs 的返回值 */
export function renderToolsDoc(specs) {
  validateMetadataCoverage(specs.map((spec) => spec.name));
  const summary = summarizeMetadata(specs);
  const lines = [];
  lines.push('# browser_* 工具索引（' + summary.total + ' 个）');
  lines.push('');
  lines.push('> GENERATED by `dsh-plugin/scripts/build-tools-doc.mjs` —— 不要手改；`--check` 会校验生成物与实现一致。');
  lines.push('> 数据来源：`lib/tools.mjs` 的工具定义 + `lib/tool-metadata.mjs` 的行为元数据。');
  lines.push('');
  lines.push('模型通过 DSH 的 `tools` 服务看到这 ' + summary.total + ' 个工具；本文件是它们的索引与安全语义：');
  lines.push('');
  lines.push('- **风险 risk**：`read` = ' + RISK_NOTE.read + '；`write` = ' + RISK_NOTE.write + '；`destructive` = ' + RISK_NOTE.destructive + '。');
  lines.push('- **幂等 idempotent**：同样参数重复调用是否等价于一次。`否` 的工具失败后先重新观察状态，不要原样重放。');
  lines.push('- **副作用 sideEffects**：' + Object.entries(SIDE_EFFECTS).map(([key, label]) => '`' + key + '`（' + label + '）').join('、') + '。');
  lines.push('- **协议方法 methods**：工具真正触达的 canonical 方法；`—` 表示纯 CLI/本地能力（与 `tests/unit/plugin-parity.test.mjs` 同口径）。');
  lines.push('- **失败后下一步**：工具语义级恢复建议；错误码级映射见 `lib/error-recovery.mjs`，失败输出会自动渲染可执行步骤。');
  lines.push('');
  lines.push('## 摘要');
  lines.push('');
  lines.push('| 项目 | 数值 |');
  lines.push('| --- | ---: |');
  lines.push('| 工具总数 | ' + summary.total + ' |');
  for (const risk of RISK_LEVELS) lines.push('| ' + RISK_LABEL[risk] + '（`' + risk + '`） | ' + summary.risks[risk] + ' |');
  lines.push('| 幂等工具 | ' + summary.idempotent + ' |');
  lines.push('| 有恢复建议的工具 | ' + summary.withRecovery + ' |');
  lines.push('');
  lines.push('副作用分布：' + (Object.keys(summary.sideEffects).length
    ? Object.entries(summary.sideEffects).map(([key, count]) => '`' + key + '`×' + count).join('、')
    : '无'));
  lines.push('');
  lines.push('## 工具（按分类）');
  lines.push('');
  const groups = groupByCategory(specs);
  for (const [category, list] of groups) {
    if (!list.length) continue;
    const meta = CATEGORIES[category];
    lines.push('### ' + meta.label + '（`' + category + '`，' + list.length + ' 个）');
    lines.push('');
    lines.push('| 工具 | 说明 | 风险 | 幂等 | 副作用 | 协议方法 | 失败后下一步 | 参考 |');
    lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const spec of list) {
      lines.push('| `' + spec.name + '` | ' + cell(spec.title) + ' | ' + riskCell(spec) + ' | ' + idempotentCell(spec)
        + ' | ' + effectsCell(spec) + ' | ' + methodsCell(spec) + ' | ' + cell(spec.recovery)
        + ' | ' + spec.docs.map((doc) => '[' + path.basename(doc, '.md') + '](skill/' + doc + ')').join('、') + ' |');
    }
    lines.push('');
  }
  lines.push('## 破坏性工具清单（调用前先向用户说明）');
  lines.push('');
  const destructive = specs.filter((spec) => spec.risk === 'destructive');
  if (!destructive.length) {
    lines.push('无。');
  } else {
    for (const spec of destructive) {
      lines.push('- `' + spec.name + '`（' + spec.categoryLabel + '）：' + spec.recovery);
    }
  }
  lines.push('');
  lines.push('## 生成与校验');
  lines.push('');
  lines.push('```powershell');
  lines.push('node dsh-plugin/scripts/build-tools-doc.mjs');
  lines.push('node dsh-plugin/scripts/build-tools-doc.mjs --check');
  lines.push('```');
  lines.push('');
  return lines.join('\n');
}

/** 生成并（默认）写盘；check=true 只比对。返回 { path, text, changed, problems }。 */
export function buildToolsDoc({ check = false } = {}) {
  const specs = buildToolSpecs(async () => ({}));
  const text = renderToolsDoc(specs);
  const problems = [];
  let current = null;
  try {
    current = fs.readFileSync(OUTPUT, 'utf8');
  } catch {
    current = null;
  }
  if (check) {
    if (current === null) problems.push('缺少生成物：' + path.relative(process.cwd(), OUTPUT));
    else if (current !== text) problems.push('生成物与实现不一致：' + path.relative(process.cwd(), OUTPUT));
    return { path: OUTPUT, text, changed: current !== text, problems };
  }
  fs.writeFileSync(OUTPUT, text, 'utf8');
  return { path: OUTPUT, text, changed: current !== text, problems };
}

function main(argv) {
  const check = argv.includes('--check');
  const result = buildToolsDoc({ check });
  if (check) {
    if (result.problems.length) {
      for (const problem of result.problems) console.error('TOOLS DOC FAILED: ' + problem);
      process.exit(1);
    }
    console.log('tools doc check: clean (' + path.relative(process.cwd(), result.path) + ')');
    return;
  }
  console.log('tools doc written: ' + path.relative(process.cwd(), result.path) + ' (' + result.text.length + ' chars)');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
