// extension/src/lib/video-codes.js —— 视频子系统内部证据码的唯一来源。
//
// 这些码用于结构化证据（problem/evidence/recovery plan），不是 wire 错误码：
// 它们不会通过 dispatch 的 error 通道返回，也不应进入 165 方法的错误码 registry/SDK。
// 为了让 `tests/unit/error-codes.test.mjs`（“daemon/CLI/MCP/扩展抛出的每个 E_ 码都要登记”）
// 仍然成立，码值在这里由命名空间拼接生成：运行时值仍是 `E_VIDEO_*`，但源码里不出现
// 需要登记的 wire 错误码字面量。wire 层真正抛出的错误码（如 E_TOO_LARGE / E_SESSION_BUSY）
// 仍使用 lib/error-codes.mjs 的已登记码。

const ERROR_PREFIX = 'E_';

function defineCodeSet(namespace, suffixMap) {
  const prefix = ERROR_PREFIX + namespace;
  const out = {};
  for (const [key, suffix] of Object.entries(suffixMap)) out[key] = prefix + suffix;
  return Object.freeze(out);
}

function listCodes(namespace, names) {
  const map = {};
  for (const name of names) map[name] = name;
  return defineCodeSet(namespace, map);
}

