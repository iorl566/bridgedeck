// ui/lib/labels.js —— 新页面能力的双语文案目录（纯函数，无 DOM/chrome 依赖）。
//
// 为什么单独一个目录？
// - 老页面（debug/audit/ops/record/longshot）的大量中文已经进了 overlay 动态文案门禁
//   （translation/dynamic-texts.mjs 的 surfaces 列表），在那里新增「中文 + 变量」的拼接
//   会被门禁拦下；新能力把文案集中在这里，用 {name} 占位符插值，页面只传 key。
// - 这样新增 UI 文案天然可单测（Node 直接 import），也顺手补齐英文，
//   不必等 12 语言包（其余语言回退英文）。
//
// 约定：
// - key 用 `域.用途` 命名；`en` 必填，`zh` 可选（缺省回退 en）。
// - 占位符形如 {count}、{page}；缺参数时原样保留 `{count}`，便于测试与排查。
// - 未知语言 → 英文（与 error-hints / a11y-dialog 的回退口径一致）。
//
// 消费点（真实）：
//   extension/ui/views/history-view.js、compare-view.js、timeline-view.js
//   extension/ui/lib/states.js、paging.js（rangeLabel）、timeline.js（chunk label）
//   extension/ui/debug.js、audit.js、ops.js、record.js、longshot.js
//   tests/unit/ui-labels.test.mjs

