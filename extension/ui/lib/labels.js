/** 语言归一化：zh/zh-TW/zh-HK 走中文，其余按英文回退（与 error-hints 的 normalizeHintLang 一致）。 */
export function normalizeLabelLang(lang) {
  const value = String(lang || '').trim().toLowerCase();
  if (!value) return 'zh';
  if (value === 'zh' || value.startsWith('zh-') || value === 'zh-tw' || value === 'zh-hk') return 'zh';
  if (value === 'en' || value.startsWith('en-')) return 'en';
  return 'en';
}

/** 全部 key（升序，便于测试与文档生成）。 */
export function labelKeys() {
  return [...new Set([...Object.keys(ZH), ...Object.keys(EN)])].sort();
}

export function hasLabel(key) {
  return Object.prototype.hasOwnProperty.call(EN, key) || Object.prototype.hasOwnProperty.call(ZH, key);
}

/** 取某语言的原始模板；未知 key 返回空串（调用方可回退到 key 本身）。 */
export function labelTemplate(key, lang) {
  const resolved = normalizeLabelLang(lang);
  if (resolved === 'zh') {
    if (Object.prototype.hasOwnProperty.call(ZH, key)) return ZH[key];
    return Object.prototype.hasOwnProperty.call(EN, key) ? EN[key] : '';
  }
  return Object.prototype.hasOwnProperty.call(EN, key) ? EN[key] : '';
}

/**
 * 占位符插值：`{name}` 用 params.name 替换；缺参数时保留 `{name}`（便于发现漏传）。
 * @param {string} template
 * @param {Record<string, unknown>} [params]
 */
export function interpolate(template, params) {
  const source = String(template === undefined || template === null ? '' : template);
  const values = params && typeof params === 'object' ? params : {};
  if (!source.includes('{')) return source;
  return source.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => {
    if (!Object.prototype.hasOwnProperty.call(values, name)) return match;
    const value = values[name];
    if (value === undefined || value === null) return match;
    return String(value);
  });
}

/**
 * 格式化一条 UI 文案。
 * @param {string} key 目录 key
 * @param {Record<string, unknown>} [params] 占位符参数
 * @param {string} [lang] 语言（默认 zh）
 * @returns {string} 未知 key 返回 key 本身，未知语言回退英文
 */
export function formatLabel(key, params, lang) {
  const template = labelTemplate(key, lang === undefined ? 'zh' : lang);
  if (!template) return String(key);
  return interpolate(template, params);
}

/** 便捷绑定：`const t = labeler(getLang()); t('paging.page', {page: 2, pages: 5})`。 */
export function labeler(lang) {
  const resolved = lang === undefined ? 'zh' : lang;
  return (key, params) => formatLabel(key, params, resolved);
}

/** 缺翻译自检：返回 zh 有而 en 没有（或反之）的 key，供测试断言目录完整性。 */
export function labelCoverage() {
  const missingEn = Object.keys(ZH).filter((key) => !Object.prototype.hasOwnProperty.call(EN, key));
  const missingZh = Object.keys(EN).filter((key) => !Object.prototype.hasOwnProperty.call(ZH, key));
  return { missingEn: missingEn.sort(), missingZh: missingZh.sort() };
}

/** 目录自检：占位符在 zh/en 中必须同集合（防止插值漏参）。 */
export function placeholderMismatch() {
  const problems = [];
  for (const key of labelKeys()) {
    const zh = labelTemplate(key, 'zh');
    const en = labelTemplate(key, 'en');
    const zhNames = [...zh.matchAll(/\{([a-zA-Z0-9_]+)\}/g)].map((match) => match[1]).sort();
    const enNames = [...en.matchAll(/\{([a-zA-Z0-9_]+)\}/g)].map((match) => match[1]).sort();
    if (zhNames.join(',') !== enNames.join(',')) problems.push({ key, zh: zhNames, en: enNames });
  }
  return problems;
}

